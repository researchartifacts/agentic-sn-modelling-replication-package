package org.snrmbench.netbench;

import org.snrmbench.netbench.schema.SchemaDoc;
import org.snrmbench.netbench.schema.Sheet;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;

import static org.assertj.core.api.Assertions.assertThat;

/** the LLM instruction file embeds the current netbench schema --format markdown output verbatim between its markers, so the prompt and the checker cannot drift. */
class LlmInstructionsTest {

    private static final Path FILE = Path.of("llm-instructions", "v1.md");
    private static final String BEGIN = "<!-- schema: generated by netbench schema --format markdown; do not edit -->\n";
    private static final String END = "<!-- /schema -->\n";

    private static String text() throws IOException {
        return Files.readString(FILE, StandardCharsets.UTF_8);
    }

    @Test
    void embedsTheCurrentSchemaVerbatimBetweenTheMarkers() throws IOException {
        String text = text();
        int begin = text.indexOf(BEGIN);
        int end = text.indexOf(END);

        assertThat(begin).as("begin marker").isNotNegative();
        assertThat(text.indexOf(BEGIN, begin + 1)).as("a second begin marker").isNegative();
        assertThat(end).as("end marker").isGreaterThan(begin);
        assertThat(text.indexOf(END, end + 1)).as("a second end marker").isNegative();
        assertThat(text.substring(begin + BEGIN.length(), end)).isEqualTo(SchemaDoc.markdown());
    }

    @Test
    void isVersionStampedAndLf() throws IOException {
        String text = text();

        assertThat(text).startsWith("---\nversion: v1\n---\n").doesNotContain("\r").endsWith("\n");
    }

    @Test
    void namesTheFiveFilesInEnvelopeOrder() throws IOException {
        String text = text();
        String envelope = text.substring(text.lastIndexOf("## Response"));

        String order = String.join(", ", Arrays.stream(Sheet.values()).map(s -> "`" + s.fileName() + "`").toList());
        assertThat(envelope).contains("level-3 heading naming the file, in this order: " + order + "; no other text.");
    }
}
